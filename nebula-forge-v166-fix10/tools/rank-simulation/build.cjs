// Compile the same ordered classic scripts into a per-account, synchronous worker function.
// Browser function declarations are hoisted one script at a time. Preserve that distinction.
const fs=require('node:fs'), path=require('node:path'), vm=require('node:vm');
const parserText=process.binding('natives')['internal/deps/acorn/acorn/dist/acorn'];
if(!parserText)throw Error('The rules compiler needs the Acorn parser shipped with Node.');
const parser=vm.runInNewContext('const exports={},module={exports};'+parserText+';exports',{});
const root=path.resolve(__dirname,'../..');
const dir=path.join(root,'dist/client');
const page=fs.existsSync(path.join(root,'web/index.html'))
 ?require('node:child_process').execFileSync(process.env.PYTHON || (process.platform==='win32'?'python':'python3'),['tools/build-web.py','--print-source'],{cwd:root,encoding:'utf8',maxBuffer:8000000})
 :fs.readFileSync(path.join(dir,'index.html'),'utf8');
const blocks=[...page.matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/g)];
// Exclude pure visual and transport modules. Their inert headless adapters are in head.js.
// Timing tables used by combat (e.g. skill-motion and archer-flight) remain actual game code.
const presentation=new Set(['secondary-art','hair-volume','secondary-motion','twilight-rain','poses','paladin-motion-art',
 'paladin-motion','skin-motion','skill-films','combat-effects','combat-motion','spell-flight','companion-cels',
 'companion-motion','ranged-combat','skin-rigs','season-rigs','boss-techniques','adventure-fx','registration',
 'enemy-unity','unity-heroes','enemy-motion','actor-motion','geometry','views','weapon-depth','weapon-appearance',
 'hatch-ritual','summon-ritual','costume-ritual','menu-materials','world-boss-motion','chat','enemy-sound','battle-presentation']);
const funcs=new Set(),chunks=[];
for(const [index,match] of blocks.entries()){
 const src=match[1].match(/src="([^"]+)"/)?.[1].split('?')[0];
 if(index===0||index===blocks.length-1||src&&/rankings\.js|verified-rank|save-guard|community|social-server|unity-battle\/enable/.test(src))continue;
 if(src&&presentation.has(path.basename(src,'.js')))continue;
 let text=src?fs.readFileSync(path.join(dir,src),'utf8'):match[2];
 const ast=parser.parse(text,{ecmaVersion:'latest',sourceType:'script'});
 const lifted=[];
 for(const node of ast.body){
  if(node.type!=='FunctionDeclaration')continue;
  funcs.add(node.id.name);
  const raw=text.slice(node.start,node.end);
  lifted.push(node.id.name+' = '+raw+';');
 }
 for(const node of ast.body.slice().reverse())if(node.type==='FunctionDeclaration')text=text.slice(0,node.start)+text.slice(node.end);
 chunks.push('// '+(src||'game script '+index)+'\n'+lifted.join('\n')+'\n'+text);
}
const header=fs.readFileSync(path.join(__dirname,'head.js'),'utf8'),runner=fs.readFileSync(path.join(__dirname,'run.js'),'utf8');
const result='// Generated by tools/rank-simulation/build.cjs from the deployed game rules.\n'+header+'\nvar '+[...funcs].join(',')+';\n'+chunks.join('\n;\n')+'\n'+runner+'\n}\n';
fs.writeFileSync(path.join(root,'dist/server/rank-simulation.js'),result);
