CREATE TABLE chat_guilds (
 guild_key TEXT PRIMARY KEY NOT NULL,
 name TEXT NOT NULL,
 founder TEXT REFERENCES nicknames(owner)
);
CREATE TABLE chat_members (
 owner TEXT PRIMARY KEY NOT NULL REFERENCES nicknames(owner),
 guild_key TEXT REFERENCES chat_guilds(guild_key)
);
CREATE TABLE chat_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 channel TEXT NOT NULL CHECK(channel IN ('world','guild','whisper')),
 sender TEXT NOT NULL REFERENCES nicknames(owner),
 recipient TEXT REFERENCES nicknames(owner),
 guild_key TEXT REFERENCES chat_guilds(guild_key),
 nonce TEXT NOT NULL,
 body TEXT NOT NULL,
 portrait BIGINT NOT NULL,
 sent_at BIGINT NOT NULL,
 UNIQUE(sender,nonce)
);
CREATE INDEX chat_room_history ON chat_messages(channel,guild_key,id);
CREATE INDEX chat_inbox ON chat_messages(channel,recipient,id);
CREATE INDEX chat_outbox ON chat_messages(sender,channel,id);
