// Sign-in checks, against a key pair made on the spot and a local stand-in for Google's key list.
import assert from 'node:assert/strict';
import http from 'node:http';
import {execFileSync} from 'node:child_process';
import {createSign} from 'node:crypto';
import {mkdtempSync,readFileSync} from 'node:fs';
import os from 'node:os';import path from 'node:path';
const dir=mkdtempSync(path.join(os.tmpdir(),'auth-'));
const make=name=>{execFileSync('openssl',['req','-x509','-newkey','rsa:2048','-nodes','-keyout',`${dir}/${name}.key`,'-out',`${dir}/${name}.crt`,'-days','2','-subj','/CN=test'],{stdio:'ignore'});
 return {key:readFileSync(`${dir}/${name}.key`,'utf8'),cert:readFileSync(`${dir}/${name}.crt`,'utf8')}};
const good=make('good'),other=make('other');
const server=http.createServer((req,res)=>{res.writeHead(200,{'Content-Type':'application/json','Cache-Control':'public, max-age=600'});res.end(JSON.stringify({k1:good.cert}))}).listen(0,'127.0.0.1');
await new Promise(r=>server.once('listening',r));
process.env.FIREBASE_CERTS_URL='http://127.0.0.1:'+server.address().port+'/';
const {firebaseUser,guestFromCookie,newGuestCookie}=await import('../host/auth.mjs');
const b64=o=>Buffer.from(JSON.stringify(o)).toString('base64url');
const token=(claims,{key=good.key,kid='k1',alg='RS256'}={})=>{const head=b64({alg,kid,typ:'JWT'})+'.'+b64(claims);return head+'.'+createSign('RSA-SHA256').update(head).sign(key,'base64url')};
const now=Math.floor(Date.now()/1000),P='my-game';
const claims={aud:P,iss:'https://securetoken.google.com/'+P,sub:'user-123',iat:now-10,auth_time:now-10,exp:now+3600};
assert.equal(await firebaseUser(token(claims),P),'user-123','a valid token names its user');
assert.equal(await firebaseUser(token({...claims,exp:now-1}),P),null,'expired');
assert.equal(await firebaseUser(token({...claims,aud:'someone-else'}),P),null,'made for another project');
assert.equal(await firebaseUser(token({...claims,iss:'https://securetoken.google.com/other'}),P),null,'wrong issuer');
assert.equal(await firebaseUser(token({...claims,sub:''}),P),null,'no user');
assert.equal(await firebaseUser(token({...claims,iat:now+4000}),P),null,'issued in the future');
assert.equal(await firebaseUser(token(claims,{key:other.key}),P),null,'signed with a key Google does not list');
assert.equal(await firebaseUser(token(claims,{kid:'unknown'}),P),null,'unknown key id');
const forged=token(claims).split('.');forged[1]=b64({...claims,sub:'admin'});
assert.equal(await firebaseUser(forged.join('.'),P),null,'payload changed after signing');
assert.equal(await firebaseUser(b64({alg:'none',kid:'k1'})+'.'+b64(claims)+'.',P),null,'unsigned token');
assert.equal(await firebaseUser('not-a-token',P),null);
const secret='test-secret-test-secret-test-secret',guest=newGuestCookie(secret,false);
assert.equal(guestFromCookie(guest.cookie.split(';')[0],secret),guest.id,'a guest cookie names its guest');
assert.equal(guestFromCookie(guest.cookie.split(';')[0],secret+'x'),null,'another secret does not accept it');
assert.equal(guestFromCookie('nebula_guest=00000000-0000-4000-8000-000000000000.'+'A'.repeat(43),secret),null,'a made-up id is refused');
server.close();
console.log('PASS sign-in: valid Firebase tokens are accepted; expired, foreign, forged and unsigned ones are refused; guest cookies cannot be made up');
